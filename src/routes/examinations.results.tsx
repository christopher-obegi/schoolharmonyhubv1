import { createFileRoute } from "@tanstack/react-router";
import { useMemo } from "react";
import { ModulePage } from "@/components/erp/module-page";
import { SectionCard } from "@/components/erp/page-header";
import type { Column } from "@/components/erp/data-table";
import { StatusBadge } from "@/components/erp/status-badge";
import { ComparisonBarChart } from "@/components/erp/charts";
import { humanize, pageHead, useList, useLookup } from "@/lib/resources";

const DESCRIPTION = "Published results, rankings and mean scores per exam.";

export const Route = createFileRoute("/examinations/results")({
  head: pageHead("Results & rankings", DESCRIPTION),
  component: Page,
});

type Row = {
  id: number;
  pos: number | string;
  name: string;
  exam: string;
  score: string;
  percentage: number;
  grade: string;
  status: string;
};

const columns: Column<Row>[] = [
  {
    key: "pos",
    header: "Pos.",
    sortable: true,
    value: (row) => (typeof row.pos === "number" ? row.pos : 1e9),
  },
  { key: "name", header: "Student", sortable: true },
  { key: "exam", header: "Exam" },
  { key: "score", header: "Score", align: "right" },
  { key: "percentage", header: "%", align: "right", sortable: true },
  { key: "grade", header: "Grade", align: "right" },
  { key: "status", header: "Status", render: (row) => <StatusBadge status={row.status} /> },
];

function Page() {
  const { data, isLoading, error } = useList("results");
  const students = useLookup("students");
  const exams = useLookup("exams");
  const subjects = useLookup("subjects");

  const rows = useMemo<Row[]>(
    () =>
      (data ?? []).map((r) => ({
        id: r.id,
        pos: Number(r.rank) || "—",
        name: students.name(r.student),
        exam: exams.name(r.exam),
        score: `${Number(r.marks_obtained)} / ${Number(r.total_marks)}`,
        percentage: Number(r.percentage),
        grade: String(r.grade || "—"),
        status: humanize(r.status),
      })),
    [data, students, exams],
  );

  /** Mean percentage per subject across all results. */
  const subjectMeans = useMemo(() => {
    const subjectOfExam = new Map(exams.rows.map((e) => [e.id, Number(e.subject)]));
    const sums = new Map<string, { total: number; n: number }>();
    for (const r of data ?? []) {
      const subject = subjects.name(subjectOfExam.get(Number(r.exam)));
      const entry = sums.get(subject) ?? { total: 0, n: 0 };
      entry.total += Number(r.percentage);
      entry.n += 1;
      sums.set(subject, entry);
    }
    return [...sums.entries()].map(([subject, { total, n }]) => ({
      subject,
      mean: Math.round((total / n) * 10) / 10,
    }));
  }, [data, exams.rows, subjects]);

  return (
    <ModulePage<Row>
      title="Results & rankings"
      description={DESCRIPTION}
      resource="results"
      columns={columns}
      rows={rows}
      loading={isLoading}
      error={error}
      searchKeys={["name", "exam"]}
      searchPlaceholder="Search students…"
      filterKey="exam"
      tableTitle="Merit list"
      emptyDescription="Results are generated by the backend once marks are entered and processed."
      above={
        <SectionCard title="Subject means" description="Average percentage per subject">
          <div className="p-4">
            {subjectMeans.length ? (
              <ComparisonBarChart
                data={subjectMeans}
                xKey="subject"
                bars={[{ key: "mean", color: "var(--color-chart-1)" }]}
              />
            ) : (
              <p className="py-10 text-center text-sm text-muted-foreground">
                {isLoading ? "Loading results…" : "No results yet."}
              </p>
            )}
          </div>
        </SectionCard>
      }
    />
  );
}
